#!/bin/sh

CURDIR=`pwd`
ARCH=`arch`
GUNUDIR=$(arch)-linux-gnu
FILESDIR="../../files"
VERSION=1.0
RELEASE1=`date +%Y`
RELEASE2=`date +%m%d`
SCANNERNAME=$1
VENDORNAME=$2
PACKAGEVERSION=$VERSION.$RELEASE1.$RELEASE2


if [ -z $VENDORNAME ]; then
	VENDORNAME="Canon"
fi
if [ -z $PACKAGEVERSION ]; then
	PACKAGEVERSION="1.0.2024.0301"
fi

rm -rf $SCANNERNAME

mkdir -p $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME
mkdir -p $SCANNERNAME/$SCANNERNAME/DEBIAN
mkdir -p $SCANNERNAME/$SCANNERNAME/etc/udev/rules.d
mkdir -p $SCANNERNAME/$SCANNERNAME/etc/sane.d/dll.d
mkdir -p $SCANNERNAME/$SCANNERNAME/usr/lib/$GUNUDIR/sane

cp $FILESDIR/80-$SCANNERNAME.rules $SCANNERNAME/$SCANNERNAME/etc/udev/rules.d
echo $SCANNERNAME > $SCANNERNAME/$SCANNERNAME/etc/sane.d/dll.d/$SCANNERNAME
cp $FILESDIR/libsane-$SCANNERNAME.so.1 $SCANNERNAME/$SCANNERNAME/usr/lib/$GUNUDIR/sane/libsane-$SCANNERNAME.so.1
cp $FILESDIR/libsane-$SCANNERNAME.so.1 $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME/libsane-$SCANNERNAME.so.1
cp $FILESDIR/CeiUSBLinux.so $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME/CeiUSBLinux.so
cp $FILESDIR/libjpeg.so $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME/libjpeg.so
cp $FILESDIR/CsdCore.so $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME
cp $FILESDIR/${SCANNERNAME}vs.so $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME/${SCANNERNAME}vs.so
cp $FILESDIR/$SCANNERNAME.ini $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME
cp $FILESDIR/$SCANNERNAME.sane.ini $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME
cp $FILESDIR/license/* $SCANNERNAME/$SCANNERNAME/opt/$VENDORNAME/$SCANNERNAME

sed -e s/SED_SCANNERNAME/$SCANNERNAME/g DEBIAN/control > $SCANNERNAME/$SCANNERNAME/DEBIAN/control.1
sed -e s/SED_PACKAGEVERSION/$PACKAGEVERSION/g $SCANNERNAME/$SCANNERNAME/DEBIAN/control.1 > $SCANNERNAME/$SCANNERNAME/DEBIAN/control
sed -e s/SED_MAINTAINER/$VENDORNAME/g $SCANNERNAME/$SCANNERNAME/DEBIAN/control > $SCANNERNAME/$SCANNERNAME/DEBIAN/control.1
mv $SCANNERNAME/$SCANNERNAME/DEBIAN/control.1 $SCANNERNAME/$SCANNERNAME/DEBIAN/control

chmod 0555 $SCANNERNAME/$SCANNERNAME/DEBIAN/*

cd $SCANNERNAME

dpkg-deb --build $SCANNERNAME

mv $SCANNERNAME.deb ${SCANNERNAME}_chromebook_${PACKAGEVERSION}.$ARCH.deb

cd ..

# echo version info
cd $CURDIR
VERFILE=$CURDIR/version.txt
echo "version" > "$VERFILE"
readelf -d $FILESDIR/libsane-$SCANNERNAME.so.1 | grep soname | sed -e "s/^.\{57\}//" >> "$VERFILE"
readelf -d $FILESDIR/CeiUSBLinux.so | grep soname | sed -e "s/^.\{57\}//" >> "$VERFILE"
readelf -d $FILESDIR/libjpeg.so | grep soname | sed -e "s/^.\{57\}//" >> "$VERFILE"
readelf -d $FILESDIR/CsdCore.so | grep soname | sed -e "s/^.\{57\}//" >> "$VERFILE"
readelf -d $FILESDIR/${SCANNERNAME}vs.so | grep soname | sed -e "s/^.\{57\}//" >> "$VERFILE"

mv $VERFILE $SCANNERNAME
